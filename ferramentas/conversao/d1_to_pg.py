"""Converte o schema SQLite (D1) do SGO para PostgreSQL no schema 'sgo' e gera dados."""
import json,re,sys
src=json.load(open(sys.argv[1])); out=sys.argv[2]; with_data=sys.argv[3]=='dados'
def conv(sql):
    s=sql
    s=re.sub(r'INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',s,flags=re.I)
    s=re.sub(r"DEFAULT \(datetime\('now'\)\)","DEFAULT (to_char(now() at time zone 'utc','YYYY-MM-DD HH24:MI:SS'))",s,flags=re.I)
    s=re.sub(r"\(unixepoch\(\) \* 1000\)","((extract(epoch from now())*1000)::bigint)",s,flags=re.I)
    s=re.sub(r'\bTEXT(\s+NOT NULL)?(\s+UNIQUE)?\s+COLLATE NOCASE',lambda m:'CITEXT'+(m.group(1) or '')+(m.group(2) or ''),s,flags=re.I)
    s=re.sub(r'\bTEXT(\s+NOT NULL\s+UNIQUE)\s+COLLATE NOCASE',r'CITEXT\1',s,flags=re.I)
    s=re.sub(r'\s+COLLATE NOCASE','',s,flags=re.I)
    s=re.sub(r'\bINTEGER\b','BIGINT',s,flags=re.I)
    s=re.sub(r'\bREAL\b','DOUBLE PRECISION',s,flags=re.I)
    s=re.sub(r'\bBLOB\b','BYTEA',s,flags=re.I)
    s=re.sub(r'--[^\n]*','',s)
    return s
L=["CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA public;","DROP SCHEMA IF EXISTS sgo CASCADE;","CREATE SCHEMA sgo;","SET search_path TO sgo, public;"]
tabs=[x for x in src['schema'] if x['type']=='table']
# ordem: respeitar REFERENCES simples
order=[];pending=tabs[:]
while pending:
    for t in pending:
        refs=set(re.findall(r'REFERENCES\s+(\w+)',t['sql'],re.I))-{t['name']}
        if refs<= {o['name'] for o in order}:
            order.append(t);pending.remove(t);break
    else: order+=pending;break
for t in order: L.append(conv(t['sql'])+";")
for x in src['schema']:
    if x['type']=='index': L.append(conv(x['sql']).replace('CREATE INDEX','CREATE INDEX IF NOT EXISTS').replace('CREATE UNIQUE INDEX','CREATE UNIQUE INDEX IF NOT EXISTS')+";")
def lit(v):
    if v is None: return "NULL"
    if isinstance(v,bool): return str(int(v))
    if isinstance(v,(int,float)): return repr(v)
    return "'"+str(v).replace("'","''")+"'"
if with_data:
    for t in order:
        rows=src['dados'].get(t['name'],[])
        for r in rows:
            L.append(f'INSERT INTO "{t["name"]}" ('+",".join(f'"{k}"' for k in r)+") VALUES ("+",".join(lit(v) for v in r.values())+");")
# acertar sequences identity
for t in order:
    if 'GENERATED BY DEFAULT AS IDENTITY' in conv(t['sql']):
        L.append(f"SELECT setval(pg_get_serial_sequence('sgo.{t['name']}','id'), GREATEST((SELECT COALESCE(MAX(id),0) FROM sgo.{t['name']}),1), (SELECT COUNT(*)>0 FROM sgo.{t['name']}));")
open(out,'w').write("\n".join(L)+"\n")
print(len(order),'tabelas')
